-- Unparsed uploads (ING-13, Phase 3b step 3).
--
-- A PDF that no layout parser recognizes is not a statement: it has no period, balances or rows.
-- It is recorded here instead, for the review queue (3c), and the statement table is unchanged.
-- Neither the file's bytes nor its text are stored: an upload is resolved by uploading the file
-- again once a parser recognizes it, which sets resolved_at and resolved_statement_id in the
-- import's transaction. resolved_at alone means dismissed (3c).
--
-- Uniqueness is per account: the same file held on two accounts gives two independent rows. At
-- most one row per account and file is open; resolved rows are history and never reopen.

CREATE TABLE unparsed_upload (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    account_id            BIGINT      NOT NULL,
    file_sha256           TEXT        NOT NULL,
    file_name             TEXT        NOT NULL,
    reason                TEXT        NOT NULL,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at           TIMESTAMPTZ,
    resolved_statement_id BIGINT,
    CONSTRAINT pk_unparsed_upload PRIMARY KEY (id),
    CONSTRAINT fk_unparsed_upload_account FOREIGN KEY (account_id) REFERENCES account (id),
    CONSTRAINT fk_unparsed_upload_resolved_statement FOREIGN KEY (resolved_statement_id)
        REFERENCES statement (id) ON DELETE SET NULL,
    CONSTRAINT ck_unparsed_upload_file_sha256 CHECK (file_sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_unparsed_upload_file_name_length CHECK (char_length(file_name) BETWEEN 1 AND 255),
    CONSTRAINT ck_unparsed_upload_reason CHECK (reason IN ('UNRECOGNIZED_LAYOUT', 'NO_TEXT_LAYER')),
    -- A resolving statement implies resolved_at; resolved_at alone means dismissed.
    CONSTRAINT ck_unparsed_upload_resolution CHECK (resolved_statement_id IS NULL OR resolved_at IS NOT NULL)
);

-- At most one open upload per account and file; also the lookup on re-upload.
CREATE UNIQUE INDEX uq_unparsed_upload_open ON unparsed_upload (account_id, file_sha256) WHERE resolved_at IS NULL;

-- For ON DELETE SET NULL when a statement is deleted.
CREATE INDEX ix_unparsed_upload_resolved_statement ON unparsed_upload (resolved_statement_id)
    WHERE resolved_statement_id IS NOT NULL;

COMMENT ON COLUMN unparsed_upload.reason IS
    'UNRECOGNIZED_LAYOUT: the PDF has text but no parser claims it; NO_TEXT_LAYER: fewer than 20 non-whitespace '
    'characters, almost certainly a scan (OCR, Phase 8).';
